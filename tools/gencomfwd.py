#!/usr/bin/env python3
"""Writes forwarding methods for COM wrapper objects (src/olevx/wmi_fwd.h).

For each interface named on the command line, every method of its C vtable
(read from Wine's headers) becomes
    static HRESULT STDMETHODCALLTYPE fw_<Iface>_<Method>(<Iface> *This, ...)
    { return INNER(<Iface>, This)->lpVtbl-><Method>(INNER(<Iface>, This), ...); }
INNER(type, This) is defined by the including file. FW_<Iface>_VTBL lists them as
designated initializers; a wrapper's vtable starts with it and then names
only the methods it changes (and IUnknown's).

usage: gencomfwd.py <out.h> <header>:<Iface>[,<Iface>...] ...
"""
import re, sys

def methods(text, iface):
    m = re.search(r'typedef struct %sVtbl \{(.*?)\} %sVtbl;' % (iface, iface), text, re.S)
    if not m:
        sys.exit('no vtable for ' + iface)
    body = m.group(1)
    out = []
    for mm in re.finditer(r'(\w[\w\s\*]*?)\s*\(STDMETHODCALLTYPE \*(\w+)\)\(\s*(.*?)\);', body, re.S):
        ret, name, params = mm.group(1).strip(), mm.group(2), mm.group(3)
        params = [p.strip() for p in re.sub(r'\s+', ' ', params).split(',')]
        out.append((ret, name, params))
    return out

def argname(p):
    return re.findall(r'(\w+)\s*(?:\[\])?$', p)[0]

def main():
    out = sys.argv[1]
    lines = ['/* Generated by tools/gencomfwd.py from Wine\'s headers - do not edit. */']
    for spec in sys.argv[2:]:
        hdr, ifaces = spec.split(':')
        text = open(hdr).read()
        for iface in ifaces.split(','):
            vt = []
            for ret, name, params in methods(text, iface):
                if name in ('QueryInterface', 'AddRef', 'Release'):
                    continue
                args = ', '.join(['INNER(%s, This)' % iface] + [argname(p) for p in params[1:]])
                lines.append('static %s STDMETHODCALLTYPE fw_%s_%s(%s)' % (ret, iface, name, ', '.join(params)))
                lines.append('{ return INNER(%s, This)->lpVtbl->%s(%s); }' % (iface, name, args))
                vt.append('.%s = fw_%s_%s' % (name, iface, name))
            lines.append('#define FW_%s_VTBL %s' % (iface, ', '.join(vt)))
    open(out, 'w').write('\n'.join(lines) + '\n')

main()
